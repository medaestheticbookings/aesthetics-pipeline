# -*- coding: utf-8 -*-
"""Add the territory availability checker to the clinic-owners landing page.

    python add_territory_check.py

A dentist types his δήμος and sees, immediately, whether the slot is free and
what it costs. That is the whole sales mechanism: scarcity he can check himself
beats a claim he has to believe.

TAKEN is the only thing to edit as slots sell. Everything else is generated
from clinic-clients/greece-territories.csv — re-run this script after changing
the territory file.

Prices follow the tier the territory file assigns:
  T1 (80k+)  1500   T2 (40-80k) 1200   T3 (20-40k) 900
A CLUSTER δήμος is too small to carry a fee alone and is quoted on request.
"""
import csv
import io
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")

HERE = os.path.dirname(os.path.abspath(__file__))
PAGE = os.path.join(HERE, "index.html")
CSV = os.path.join(HERE, "..", "..", "clinic-clients", "greece-territories.csv")

# δήμοι already sold. Add a line the day one is paid for, then re-run.
TAKEN = {
    # "Γλυφάδα": "Οδοντιατρείο Χ",
}

MARKER = '<p class="eyebrow">Το πραγματικό πρόβλημα</p>'

CSS = """
  /* territory availability checker */
  .terr-box{max-width:620px;margin:0 auto;}
  .terr-in{width:100%;padding:16px 18px;font-size:17px;font-family:inherit;
    border:2px solid var(--line);border-radius:12px;background:var(--card);
    color:var(--ink);font-weight:600;}
  .terr-in:focus{outline:none;border-color:var(--teal);}
  .terr-out{margin-top:18px;min-height:10px;}
  .terr-card{border-radius:14px;padding:22px 24px;text-align:left;}
  .terr-free{background:var(--teal);color:#fff;}
  .terr-gone{background:var(--cream-alt);color:var(--ink);border:1px solid var(--line);}
  .terr-head{font-size:22px;font-weight:800;letter-spacing:-.02em;margin-bottom:6px;}
  .terr-sub{font-size:15px;opacity:.9;margin-bottom:16px;}
  .terr-price{font-size:34px;font-weight:800;letter-spacing:-.03em;}
  .terr-price span{font-size:15px;font-weight:600;opacity:.85;}
  .terr-free .terr-cta{display:inline-block;margin-top:16px;background:var(--brass-lift);
    color:#1A1108;font-weight:800;padding:13px 26px;border-radius:999px;text-decoration:none;}
  .terr-note{font-size:13px;color:var(--ink-soft);margin-top:14px;text-align:center;}
"""

SECTION = """
<section id="perioxi">
  <div class="wrap">
    <div class="sec-head">
      <p class="eyebrow">Διαθεσιμότητα</p>
      <h2>Είναι ελεύθερη η περιοχή σου;</h2>
      <p>Συνεργάζομαι με <b>ένα οδοντιατρείο ανά δήμο</b>. Γράψε τον δικό σου και δες το αμέσως.</p>
    </div>
    <div class="terr-box">
      <input class="terr-in" id="terr-in" list="terr-dimoi" autocomplete="off"
             placeholder="Γράψε τον δήμο σου…">
      <datalist id="terr-dimoi">__OPTIONS__</datalist>
      <div class="terr-out" id="terr-out"></div>
      <p class="terr-note">332 δήμοι. Μία θέση στον καθένα.</p>
    </div>
  </div>
</section>

<script>
/* Generated by add_territory_check.py — do not hand-edit TERR or TAKEN here. */
var TERR = {__TIERS__};
var TAKEN = {__TAKEN__};
var PRICE = {T1:1500, T2:1200, T3:900};
(function(){
  var box = document.getElementById('terr-in');
  var out = document.getElementById('terr-out');
  if(!box || !out) return;

  function render(){
    var name = box.value.trim();
    if(!name){ out.innerHTML=''; return; }
    var tier = TERR[name];
    if(!tier){
      out.innerHTML = '<div class="terr-card terr-gone"><div class="terr-head">'
        + 'Δεν βρήκα αυτόν τον δήμο</div><div class="terr-sub">Διάλεξε από τη λίστα '
        + 'καθώς γράφεις, ή στείλε μου μήνυμα και το κοιτάω.</div></div>';
      return;
    }
    if(TAKEN[name]){
      out.innerHTML = '<div class="terr-card terr-gone"><div class="terr-head">'
        + name + ' — κλεισμένη</div><div class="terr-sub">Η θέση έχει δοθεί. '
        + 'Μπορώ να σε βάλω σε λίστα αναμονής, ή να δούμε γειτονικό δήμο.</div>'
        + '<a href="#form" class="btn">Λίστα αναμονής</a></div>';
      return;
    }
    if(tier === 'CLUSTER'){
      out.innerHTML = '<div class="terr-card terr-free"><div class="terr-head">'
        + name + ' — ελεύθερη</div><div class="terr-sub">Μικρός δήμος, οπότε '
        + 'συνδυάζεται με τον διπλανό. Η τιμή βγαίνει μαζί.</div>'
        + '<a href="#form" class="terr-cta">Ζήτα τιμή</a></div>';
      return;
    }
    out.innerHTML = '<div class="terr-card terr-free"><div class="terr-head">'
      + name + ' — ελεύθερη</div>'
      + '<div class="terr-sub">Ασθενείς που ψάχνουν ήδη λεύκανση, στο κινητό σου. '
      + 'Εσύ τηλεφωνείς και κλείνεις το ραντεβού.</div>'
      + '<div class="terr-price">€' + PRICE[tier] + '<span> /μήνα, όλα μέσα</span></div>'
      + '<a href="#form" class="terr-cta">Κράτα τη θέση</a></div>';
  }
  box.addEventListener('input', render);
  box.addEventListener('change', render);
})();
</script>
"""


def main():
    rows = sorted(csv.DictReader(io.open(CSV, encoding="utf-8-sig")),
                  key=lambda r: r["dimos"])
    options = "".join('<option value="%s">' % r["dimos"] for r in rows)
    tiers = ",".join('"%s":"%s"' % (r["dimos"], r["tier"]) for r in rows)
    taken = ",".join('"%s":1' % k for k in TAKEN)

    s = io.open(PAGE, encoding="utf-8").read()
    if "terr-box" in s:
        sys.exit("already present — remove the old section first")
    if s.count(MARKER) != 1:
        sys.exit("ABORT: insertion marker found %d times" % s.count(MARKER))

    section = (SECTION.replace("__OPTIONS__", options)
                      .replace("__TIERS__", tiers)
                      .replace("__TAKEN__", taken))

    # the section goes in front of "Το πραγματικό πρόβλημα", straight after the
    # exclusivity band: he reads "one practice per area", then checks his own
    i = s.rindex("<section", 0, s.index(MARKER))
    s = s[:i] + section.strip() + "\n\n" + s[i:]

    anchor = "  .mid-cta{"
    if s.count(anchor) != 1:
        sys.exit("ABORT: css anchor")
    s = s.replace(anchor, CSS.strip("\n") + "\n" + anchor)

    io.open(PAGE, "w", encoding="utf-8", newline="\n").write(s)
    print("added the availability checker")
    print("  δήμοι in the picker : %d" % len(rows))
    print("  marked taken        : %d" % len(TAKEN))


if __name__ == "__main__":
    main()
